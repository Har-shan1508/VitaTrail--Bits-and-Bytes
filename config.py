"""Settings and secrets. Everything is configurable through environment variables."""
import base64
import hashlib
import json
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA_DIR = Path(os.getenv("DATA_DIR", ROOT / "data"))
DATA_DIR.mkdir(parents=True, exist_ok=True)
DB_PATH = DATA_DIR / "vitatrail.db"
FRONTEND_DIR = ROOT / "frontend"

DEMO_MODE = os.getenv("DEMO_MODE", "1") == "1"  # enables reset + tamper demo endpoints
SESSION_HOURS = 8
MAX_PIN_FAILS = 5


def _load_secrets():
    """SECRET_KEY signs JWTs. MASTER_KEY wraps patient data keys and hospital signing keys.

    Both come from the environment in production. If they are missing we generate them once
    into data/secrets.json so a local demo "just works". The master key is passed through
    SHA-256 so any high-entropy string (e.g. one generated by a hosting platform) is accepted.
    """
    path = DATA_DIR / "secrets.json"
    stored = json.loads(path.read_text()) if path.exists() else {}
    secret = os.getenv("SECRET_KEY") or stored.get("secret_key")
    master = os.getenv("MASTER_KEY") or stored.get("master_key")
    fresh = {}
    if not secret:
        secret = fresh["secret_key"] = secrets.token_urlsafe(48)
    if not master:
        master = fresh["master_key"] = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()
    if fresh:
        path.write_text(json.dumps({**stored, **fresh}))
    return secret, hashlib.sha256(master.encode()).digest()


SECRET_KEY, MASTER_KEY = _load_secrets()
